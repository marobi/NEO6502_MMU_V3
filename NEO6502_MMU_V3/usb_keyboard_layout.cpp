static USBKeyboardLocale g_keyboardLocale = USB_KEYBOARD_DEFAULT_LOCALE;
static const USBKeyboardLayoutTable* g_activeLayout = nullptr;

static bool usb_keyboard_shift_active(uint8_t modifier) {
  return (modifier & (KEYBOARD_MODIFIER_LEFTSHIFT | KEYBOARD_MODIFIER_RIGHTSHIFT)) != 0;
}

static bool usb_keyboard_ctrl_active(uint8_t modifier) {
  return (modifier & (KEYBOARD_MODIFIER_LEFTCTRL | KEYBOARD_MODIFIER_RIGHTCTRL)) != 0;
}

static const USBKeyboardLayoutTable* usb_keyboard_builtin_layout_for_locale(USBKeyboardLocale locale) {
  switch (locale) {
    case USB_KEYBOARD_LOCALE_DE: return &g_deLayout;
    case USB_KEYBOARD_LOCALE_US:
    default:                    return &g_usLayout;
  }
}

void usb_keyboard_set_locale(USBKeyboardLocale locale) {
  switch (locale) {
    case USB_KEYBOARD_LOCALE_US:
    case USB_KEYBOARD_LOCALE_DE:
      g_keyboardLocale = locale;
      g_activeLayout = usb_keyboard_builtin_layout_for_locale(locale);
      break;
    default:
      g_keyboardLocale = USB_KEYBOARD_LOCALE_US;
      g_activeLayout = &g_usLayout;
      break;
  }
}

USBKeyboardLocale usb_keyboard_get_locale() {
  return g_keyboardLocale;
}

static const USBKeyboardLayoutTable* usb_keyboard_active_layout() {
  if (!g_activeLayout)
    g_activeLayout = usb_keyboard_builtin_layout_for_locale(g_keyboardLocale);

  return g_activeLayout ? g_activeLayout : &g_usLayout;
}

const char* usb_keyboard_get_locale_name() {
  return usb_keyboard_active_layout()->name;
}

const USBKeyboardLayoutTable* usb_keyboard_get_active_layout_table() {
  return usb_keyboard_active_layout();
}

bool usb_keyboard_set_active_layout_table(const USBKeyboardLayoutTable* layout) {
  if (!layout) {
    usb_keyboard_set_locale(USB_KEYBOARD_DEFAULT_LOCALE);
    return false;
  }

  g_activeLayout = layout;

  if (layout == &g_deLayout)
    g_keyboardLocale = USB_KEYBOARD_LOCALE_DE;
  else if (layout == &g_usLayout)
    g_keyboardLocale = USB_KEYBOARD_LOCALE_US;
  else
    g_keyboardLocale = USB_KEYBOARD_LOCALE_CUSTOM;

  return true;
}

uint8_t usb_keyboard_keycode_to_ascii_locale(uint8_t keycode, uint8_t modifier) {
  const USBKeyboardLayoutTable* layout = usb_keyboard_active_layout();

  if (keycode >= USB_KEYBOARD_LAYOUT_KEY_COUNT)
    return 0;

  if (usb_keyboard_ctrl_active(modifier))
    return layout->ctrl[keycode];

  if (usb_keyboard_shift_active(modifier))
    return layout->shifted[keycode];

  return layout->normal[keycode];
}
